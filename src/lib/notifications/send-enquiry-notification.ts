import { emailConfig } from "@/config/email";
import { escapeHtml, safeText, sendOperationalNotificationEmail } from "@/lib/notifications/email-client";

export type EnquiryNotificationPayload = {
  enquiryId: string;
  name: string;
  email: string;
  telephone?: string | null;
  companyName?: string | null;
  category: string;
  message: string;
  source: string;
  submittedAt: Date;
  utm?: {
    source?: string | null;
    medium?: string | null;
    campaign?: string | null;
  };
};

function row(label: string, value: string | null | undefined) {
  return `<tr><th align="left" style="padding: 6px 12px 6px 0; vertical-align: top;">${escapeHtml(label)}</th><td style="padding: 6px 0;">${escapeHtml(safeText(value))}</td></tr>`;
}

function notificationAppUrl(path: string) {
  return new URL(path, emailConfig.appUrl).toString();
}

function enquiryNotificationHtml(payload: EnquiryNotificationPayload) {
  return `
    <div style="font-family: Arial, sans-serif; color: #24302f; line-height: 1.6;">
      <p style="font-size: 14px; color: #0f766e; font-weight: 700; margin: 0 0 12px;">Business Sorted</p>
      <h1 style="font-size: 22px; margin: 0 0 16px;">New Business Sorted Enquiry</h1>
      <table style="border-collapse: collapse; font-size: 14px;">
        ${row("Name", payload.name)}
        ${row("Email", payload.email)}
        ${row("Telephone", payload.telephone)}
        ${row("Company or business", payload.companyName)}
        ${row("Category", payload.category)}
        ${row("Page or form", payload.source)}
        ${row("Submission date and time", payload.submittedAt.toISOString())}
        ${row("Enquiry ID", payload.enquiryId)}
        ${row("UTM source", payload.utm?.source)}
        ${row("UTM medium", payload.utm?.medium)}
        ${row("UTM campaign", payload.utm?.campaign)}
      </table>
      <h2 style="font-size: 16px; margin: 18px 0 8px;">Message</h2>
      <p style="white-space: pre-wrap; border: 1px solid #dce7e4; border-radius: 6px; padding: 12px;">${escapeHtml(payload.message)}</p>
      <p><a href="${escapeHtml(notificationAppUrl("/support"))}">Open support page</a></p>
      <p style="font-size: 13px; color: #5f6f6b;">Operational notification generated by Business Sorted.</p>
    </div>
  `;
}

function enquiryNotificationText(payload: EnquiryNotificationPayload) {
  return [
    "New Business Sorted Enquiry",
    "",
    `Name: ${payload.name}`,
    `Email: ${payload.email}`,
    `Telephone: ${safeText(payload.telephone)}`,
    `Company or business: ${safeText(payload.companyName)}`,
    `Category: ${payload.category}`,
    `Page or form: ${payload.source}`,
    `Submission date and time: ${payload.submittedAt.toISOString()}`,
    `Enquiry ID: ${payload.enquiryId}`,
    `UTM source: ${safeText(payload.utm?.source)}`,
    `UTM medium: ${safeText(payload.utm?.medium)}`,
    `UTM campaign: ${safeText(payload.utm?.campaign)}`,
    "",
    "Message:",
    payload.message
  ].join("\n");
}

export async function sendEnquiryNotification(payload: EnquiryNotificationPayload) {
  await sendOperationalNotificationEmail({
    subject: "New Business Sorted Enquiry",
    html: enquiryNotificationHtml(payload),
    text: enquiryNotificationText(payload),
    idempotencyKey: `enquiry-${payload.enquiryId}`,
    replyTo: payload.email
  });
}
