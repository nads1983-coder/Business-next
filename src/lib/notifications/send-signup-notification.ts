import { emailConfig } from "@/config/email";
import { escapeHtml, safeText, sendOperationalNotificationEmail } from "@/lib/notifications/email-client";

export type SignupNotificationPayload = {
  userId: string;
  name?: string | null;
  email: string;
  companyName?: string | null;
  source?: string;
  submittedAt: Date;
  utm?: {
    source?: string | null;
    medium?: string | null;
    campaign?: string | null;
  };
};

function row(label: string, value: string | null | undefined) {
  return `<tr><th align="left" style="padding: 6px 12px 6px 0;">${escapeHtml(label)}</th><td style="padding: 6px 0;">${escapeHtml(safeText(value))}</td></tr>`;
}

function notificationAppUrl(path: string) {
  return new URL(path, emailConfig.appUrl).toString();
}

function signupNotificationHtml(payload: SignupNotificationPayload) {
  const adminHref = notificationAppUrl("/app/admin");

  return `
    <div style="font-family: Arial, sans-serif; color: #24302f; line-height: 1.6;">
      <p style="font-size: 14px; color: #0f766e; font-weight: 700; margin: 0 0 12px;">Business Sorted</p>
      <h1 style="font-size: 22px; margin: 0 0 16px;">New Business Sorted Sign-Up</h1>
      <table style="border-collapse: collapse; font-size: 14px;">
        ${row("Name", payload.name)}
        ${row("Email", payload.email)}
        ${row("Company or business", payload.companyName)}
        ${row("Account/user ID", payload.userId)}
        ${row("Sign-up date and time", payload.submittedAt.toISOString())}
        ${row("Source", payload.source)}
        ${row("UTM source", payload.utm?.source)}
        ${row("UTM medium", payload.utm?.medium)}
        ${row("UTM campaign", payload.utm?.campaign)}
      </table>
      <p><a href="${escapeHtml(adminHref)}">Open admin overview</a></p>
      <p style="font-size: 13px; color: #5f6f6b;">Operational notification generated by Business Sorted.</p>
    </div>
  `;
}

function signupNotificationText(payload: SignupNotificationPayload) {
  return [
    "New Business Sorted Sign-Up",
    "",
    `Name: ${safeText(payload.name)}`,
    `Email: ${payload.email}`,
    `Company or business: ${safeText(payload.companyName)}`,
    `Account/user ID: ${payload.userId}`,
    `Sign-up date and time: ${payload.submittedAt.toISOString()}`,
    `Source: ${safeText(payload.source)}`,
    `UTM source: ${safeText(payload.utm?.source)}`,
    `UTM medium: ${safeText(payload.utm?.medium)}`,
    `UTM campaign: ${safeText(payload.utm?.campaign)}`,
    `Admin overview: ${notificationAppUrl("/app/admin")}`
  ].join("\n");
}

export async function sendSignupNotification(payload: SignupNotificationPayload) {
  await sendOperationalNotificationEmail({
    subject: "New Business Sorted Sign-Up",
    html: signupNotificationHtml(payload),
    text: signupNotificationText(payload),
    idempotencyKey: `signup-${payload.userId}`,
    replyTo: emailConfig.replyTo
  });
}
